import { useState, type FormEvent } from 'react'
import { X, ShoppingBag } from 'lucide-react'
import type { ShoppingListItem, ShoppingPriority } from '../types/shopping'
import type { InventoryItem, InventoryUnit } from '../types/inventory'
import { SUPPORTED_UNITS } from '../utils/units'
import { validateAmount } from '../utils/money'

interface AddShoppingItemModalProps {
  isOpen: boolean
  onClose: () => void
  onAdd: (item: Omit<ShoppingListItem, 'id' | 'createdAt'>) => Promise<void>
  existingInventory?: InventoryItem[]
}

export function AddShoppingItemModal({
  isOpen,
  onClose,
  onAdd,
  existingInventory = [],
}: AddShoppingItemModalProps) {
  const [productName, setProductName] = useState('')
  const [inventoryItemId, setInventoryItemId] = useState('')
  const [quantity, setQuantity] = useState('1')
  const [unit, setUnit] = useState<InventoryUnit>('pcs')
  const [estimatedPriceRupees, setEstimatedPriceRupees] = useState('')
  const [priority, setPriority] = useState<ShoppingPriority>('medium')
  const [reason, setReason] = useState('')
  const [purchaseDeadline, setPurchaseDeadline] = useState('')
  const [isEssential, setIsEssential] = useState(false)
  const [isSubmitting, setIsSubmitting] = useState(false)
  const [errorMessage, setErrorMessage] = useState<string | null>(null)

  if (!isOpen) return null

  // If user selects an existing inventory item, prepopulate name, unit, and price
  const handleSelectInventoryItem = (id: string) => {
    setInventoryItemId(id)
    if (!id) return
    const match = existingInventory.find((inv) => inv.id === id)
    if (match) {
      setProductName(match.name)
      setUnit(match.unit)
      if (match.purchasePricePaise) {
        setEstimatedPriceRupees((match.purchasePricePaise / 100).toFixed(2))
      }
      setIsEssential(match.category !== 'Clothing')
    }
  }

  const handleSubmit = async (e: FormEvent) => {
    e.preventDefault()
    setErrorMessage(null)

    if (!productName.trim()) {
      setErrorMessage('Product name is required.')
      return
    }

    const parsedQty = parseFloat(quantity)
    if (isNaN(parsedQty) || parsedQty <= 0) {
      setErrorMessage('Quantity must be greater than zero.')
      return
    }

    let estimatedPricePaise: number | undefined = undefined
    if (estimatedPriceRupees.trim() !== '') {
      const val = validateAmount(estimatedPriceRupees)
      if (!val.valid) {
        setErrorMessage(val.error || 'Invalid estimated price.')
        return
      }
      estimatedPricePaise = val.paise
    }

    setIsSubmitting(true)
    try {
      await onAdd({
        productName: productName.trim(),
        inventoryItemId: inventoryItemId || undefined,
        quantity: parsedQty,
        unit,
        estimatedPricePaise,
        priority,
        reason: reason.trim() || (isEssential ? 'Essential supply restock' : 'Planned purchase'),
        status: 'planned',
        purchaseDeadline: purchaseDeadline ? new Date(purchaseDeadline).toISOString() : undefined,
        isEssential,
        isAutoGenerated: false,
      })
      onClose()
    } catch (err) {
      setErrorMessage(err instanceof Error ? err.message : 'Failed to add item.')
    } finally {
      setIsSubmitting(false)
    }
  }

  return (
    <div className="backdrop" role="dialog" aria-modal="true" aria-labelledby="add-shop-title">
      <div className="modal" style={{ width: 'min(100%, 480px)' }}>
        <header>
          <div>
            <span style={{ display: 'flex', alignItems: 'center', gap: '5px' }}>
              <ShoppingBag size={12} color="var(--bright)" />
              SMART SHOPPING LIST
            </span>
            <h2 id="add-shop-title">Add Shopping Item</h2>
          </div>
          <button type="button" className="icon-button" onClick={onClose} aria-label="Close dialog">
            <X size={20} />
          </button>
        </header>

        {errorMessage && (
          <div
            style={{
              marginTop: '10px',
              padding: '8px 12px',
              borderRadius: '8px',
              background: 'rgba(248, 113, 113, 0.16)',
              border: '1px solid rgba(248, 113, 113, 0.4)',
              color: '#fca5a5',
              fontSize: '11px',
            }}
          >
            {errorMessage}
          </div>
        )}

        <form onSubmit={handleSubmit} style={{ marginTop: '14px' }}>
          {existingInventory.length > 0 && (
            <label>
              Link to Existing Inventory Item (Optional)
              <select
                value={inventoryItemId}
                onChange={(e) => handleSelectInventoryItem(e.target.value)}
              >
                <option value="">-- None (New custom product) --</option>
                {existingInventory.map((inv) => (
                  <option key={inv.id} value={inv.id}>
                    {inv.name} (Currently {inv.quantity} {inv.unit})
                  </option>
                ))}
              </select>
            </label>
          )}

          <label>
            Product Name *
            <input
              type="text"
              placeholder="e.g. Bathing Soap, Running Shoes"
              value={productName}
              onChange={(e) => setProductName(e.target.value)}
              required
            />
          </label>

          <div className="form-grid">
            <label>
              Quantity to Buy *
              <input
                type="number"
                step="any"
                min="0.01"
                value={quantity}
                onChange={(e) => setQuantity(e.target.value)}
                required
              />
            </label>

            <label>
              Unit *
              <select value={unit} onChange={(e) => setUnit(e.target.value as InventoryUnit)}>
                {SUPPORTED_UNITS.map((u) => (
                  <option key={u} value={u}>
                    {u}
                  </option>
                ))}
              </select>
            </label>
          </div>

          <div className="form-grid">
            <label>
              Est. Unit Price (₹)
              <input
                type="number"
                step="0.01"
                min="0"
                placeholder="e.g. 150.00"
                value={estimatedPriceRupees}
                onChange={(e) => setEstimatedPriceRupees(e.target.value)}
              />
            </label>

            <label>
              Priority *
              <select value={priority} onChange={(e) => setPriority(e.target.value as ShoppingPriority)}>
                <option value="highest">Highest (Out-of-stock essential)</option>
                <option value="high">High (Running low)</option>
                <option value="medium">Medium (Regular planned)</option>
                <option value="low">Low (Optional want / discretionary)</option>
              </select>
            </label>
          </div>

          <div className="form-grid">
            <label>
              Purchase Deadline (Optional)
              <input
                type="date"
                value={purchaseDeadline}
                onChange={(e) => setPurchaseDeadline(e.target.value)}
              />
            </label>

            <label style={{ display: 'flex', alignItems: 'center', gap: '8px', cursor: 'pointer', marginTop: '20px' }}>
              <input
                type="checkbox"
                checked={isEssential}
                onChange={(e) => setIsEssential(e.target.checked)}
              />
              <span style={{ fontSize: '11px', color: 'var(--text)' }}>Mark as Essential</span>
            </label>
          </div>

          <label>
            Reason / Need Justification
            <input
              type="text"
              placeholder="e.g. Current stock completely depleted, needed for weekly meal prep"
              value={reason}
              onChange={(e) => setReason(e.target.value)}
            />
          </label>

          <div style={{ display: 'flex', justifyContent: 'flex-end', gap: '8px', marginTop: '16px' }}>
            <button type="button" className="outline-button" onClick={onClose} disabled={isSubmitting}>
              Cancel
            </button>
            <button type="submit" className="primary-button" disabled={isSubmitting}>
              {isSubmitting ? 'Adding...' : 'Add to Shopping List'}
            </button>
          </div>
        </form>
      </div>
    </div>
  )
}
