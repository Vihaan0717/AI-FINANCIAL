import { useState, useEffect, useMemo, useCallback } from 'react'
import type {
  ShoppingListItem,
  BudgetAwareShoppingEvaluation,
} from '../types/shopping'
import type { InventoryItem } from '../types/inventory'
import type { Transaction } from '../types/transaction'
import type { ReceiptInventoryLink } from '../types/receipt'
import {
  IndexedDBShoppingRepository,
  InMemoryShoppingRepository,
  type IShoppingRepository,
} from '../storage/shoppingRepository'
import {
  generateRecommendationsFromInventory,
  evaluateShoppingBudget,
} from '../utils/shoppingCalculations'
import { DEMO_SHOPPING_ITEMS } from '../utils/demoInventory'

let shopRepoInstance: IShoppingRepository
let isShopDbPersistent = true

try {
  shopRepoInstance = new IndexedDBShoppingRepository()
} catch {
  shopRepoInstance = new InMemoryShoppingRepository()
  isShopDbPersistent = false
}

export function useShoppingList() {
  const [realItems, setRealItems] = useState<ShoppingListItem[]>([])
  const [isDemoMode] = useState<boolean>(false)
  const [loading, setLoading] = useState<boolean>(true)
  const [error, setError] = useState<string | null>(null)
  const [storageWarning, setStorageWarning] = useState<string | null>(null)

  const loadItems = useCallback(async () => {
    try {
      setLoading(true)
      setError(null)
      const data = await shopRepoInstance.getAll()
      setRealItems(data)
      if (!isShopDbPersistent || !shopRepoInstance.isStoragePersistent()) {
        setStorageWarning('IndexedDB is unavailable. Shopping list is stored in temporary memory.')
      }
    } catch (err) {
      console.error('Failed to load shopping list from IndexedDB:', err)
      shopRepoInstance = new InMemoryShoppingRepository()
      isShopDbPersistent = false
      setStorageWarning('IndexedDB storage failed. Changes will NOT survive browser reload.')
      setRealItems([])
    } finally {
      setLoading(false)
    }
  }, [])

  useEffect(() => {
    loadItems()
  }, [loadItems])

  const currentItems = useMemo(() => {
    return isDemoMode ? DEMO_SHOPPING_ITEMS : realItems
  }, [isDemoMode, realItems])

  const addItem = async (
    itemData: Omit<ShoppingListItem, 'id' | 'createdAt'>
  ): Promise<ShoppingListItem> => {
    if (isDemoMode) {
      const demoNew: ShoppingListItem = {
        ...itemData,
        id: `demo_shop_${Date.now()}`,
        createdAt: new Date().toISOString(),
        isDemo: true,
      }
      setRealItems((prev) => [demoNew, ...prev])
      return demoNew
    }

    const created = await shopRepoInstance.add(itemData)
    setRealItems((prev) => [created, ...prev])
    return created
  }

  const updateItem = async (
    id: string,
    updates: Partial<ShoppingListItem>
  ): Promise<ShoppingListItem> => {
    if (isDemoMode) {
      let updated: ShoppingListItem | null = null
      setRealItems((prev) =>
        prev.map((it) => {
          if (it.id === id) {
            updated = { ...it, ...updates, updatedAt: new Date().toISOString() }
            return updated
          }
          return it
        })
      )
      if (!updated) throw new Error('Shopping item not found')
      return updated
    }

    const updated = await shopRepoInstance.update(id, updates)
    setRealItems((prev) => prev.map((it) => (it.id === id ? updated : it)))
    return updated
  }

  const deleteItem = async (id: string): Promise<void> => {
    if (isDemoMode) {
      setRealItems((prev) => prev.filter((it) => it.id !== id))
      return
    }

    await shopRepoInstance.delete(id)
    setRealItems((prev) => prev.filter((it) => it.id !== id))
  }

  // Sync recommendations from current inventory
  const syncRecommendationsFromInventory = async (
    inventory: InventoryItem[]
  ): Promise<number> => {
    const recs = generateRecommendationsFromInventory(inventory, currentItems)
    let addedCount = 0

    for (const rec of recs) {
      await addItem({
        productName: rec.productName,
        inventoryItemId: rec.inventoryItemId,
        quantity: rec.quantity,
        unit: rec.unit,
        estimatedPricePaise: rec.estimatedPricePaise,
        priority: rec.priority,
        reason: rec.reason,
        status: 'planned',
        isEssential: rec.isEssential,
        isAutoGenerated: true,
      })
      addedCount++
    }

    return addedCount
  }

  const hasReceiptInventoryUpdate = async (receiptId: string): Promise<boolean> => {
    return shopRepoInstance.hasReceiptInventoryUpdate(receiptId)
  }

  const recordReceiptInventoryUpdate = async (link: ReceiptInventoryLink): Promise<void> => {
    return shopRepoInstance.recordReceiptInventoryUpdate(link)
  }

  const evaluateBudget = (
    transactions: Transaction[],
    userBudgetLimitPaise?: number
  ): BudgetAwareShoppingEvaluation => {
    return evaluateShoppingBudget(currentItems, transactions, userBudgetLimitPaise)
  }

  return {
    shoppingList: currentItems,
    loading,
    error,
    storageWarning,
    isPersistent: isShopDbPersistent,
    addItem,
    updateItem,
    deleteItem,
    syncRecommendationsFromInventory,
    hasReceiptInventoryUpdate,
    recordReceiptInventoryUpdate,
    evaluateBudget,
    reload: loadItems,
  }
}
