import type { InventoryUnit } from './inventory'

export type ShoppingPriority = 'highest' | 'high' | 'medium' | 'low'
export type ShoppingItemStatus = 'planned' | 'purchased' | 'skipped' | 'cancelled'

export interface ShoppingListItem {
  id: string
  productName: string
  inventoryItemId?: string
  quantity: number
  unit: InventoryUnit
  estimatedPricePaise?: number
  priority: ShoppingPriority
  reason: string
  status: ShoppingItemStatus
  createdAt: string // ISO 8601
  updatedAt?: string // ISO 8601
  purchaseDeadline?: string
  isEssential?: boolean
  isAutoGenerated?: boolean
  isDemo?: boolean
  linkedReceiptId?: string
  linkedTransactionId?: string
}

export type PurchaseResolutionOption =
  | 'inventory_only'
  | 'transaction_only'
  | 'both'
  | 'neither'

export interface PurchaseConfirmationChoice {
  itemId: string
  resolution: PurchaseResolutionOption
  actualPricePaise?: number
  quantityPurchased?: number
  category?: string
  paymentMethod?: string
}

export interface BudgetAwareShoppingEvaluation {
  plannedShoppingCostsPaise: number
  confirmedSpendingPaise: number
  pendingTransactionsPaise: number
  userBudgetLimitPaise?: number // Undefined if no user budget configured
  estimatedSpendableBufferPaise: number
  hasBudgetConfigured: boolean
  isAffordable: boolean | 'unknown'
  summaryExplanation: string
  warnings: string[]
}
