import type { InventoryItem } from '../types/inventory'
import type {
  ShoppingListItem,
  ShoppingPriority,
  BudgetAwareShoppingEvaluation,
} from '../types/shopping'
import type { Transaction } from '../types/transaction'
import { calculateFinancialSummary } from './calculations'
import { calculateStockStatus } from './inventoryCalculations'
import { addPaise, formatPaise } from './money'

/**
 * Generates transparent, deterministic shopping recommendations from current inventory items.
 * Rules:
 * - Out-of-stock essential: HIGHEST priority.
 * - Consumable below threshold: HIGH priority.
 * - Adequately stocked item: NEVER recommended automatically.
 * - Expiring soon: Consumption reminder, NOT automatically a purchase recommendation unless also below threshold.
 * - Clothing/non-essential: LOW priority unless threshold explicitly breached.
 */
export function generateRecommendationsFromInventory(
  inventory: InventoryItem[],
  existingShoppingList: ShoppingListItem[] = []
): ShoppingListItem[] {
  const existingItemMap = new Map<string, ShoppingListItem>()
  for (const s of existingShoppingList) {
    if (s.inventoryItemId && s.status === 'planned') {
      existingItemMap.set(s.inventoryItemId, s)
    }
  }

  const recommendations: ShoppingListItem[] = []

  for (const item of inventory) {
    if (item.archived) continue

    // If item is already on the planned shopping list, do not duplicate
    if (existingItemMap.has(item.id)) continue

    const { status, isExpiringSoon, daysUntilExpiry } = calculateStockStatus(item)

    // 1. Out of stock item
    if (status === 'out_of_stock') {
      const isEssential = item.category !== 'Clothing'
      const priority: ShoppingPriority = isEssential ? 'highest' : 'low'
      const targetQty = item.minThreshold && item.minThreshold > 0 ? item.minThreshold * 2 : 1

      recommendations.push({
        id: `rec_oos_${item.id}_${Date.now()}`,
        productName: item.name,
        inventoryItemId: item.id,
        quantity: targetQty,
        unit: item.unit,
        estimatedPricePaise: item.purchasePricePaise,
        priority,
        reason: isEssential
          ? `Out-of-stock essential: ${item.name} is completely depleted (0 ${item.unit} on hand).`
          : `Out of stock: ${item.name} has 0 ${item.unit} remaining.`,
        status: 'planned',
        createdAt: new Date().toISOString(),
        isEssential,
        isAutoGenerated: true,
      })
      continue
    }

    // 2. Consumable below threshold
    if (status === 'running_low') {
      const isEssential = item.category !== 'Clothing'
      const priority: ShoppingPriority = isEssential ? 'high' : 'low'
      const deficiency = (item.minThreshold ?? 1) - item.quantity
      const suggestedQty = deficiency > 0 ? Math.max(1, Math.ceil(deficiency)) : 1

      recommendations.push({
        id: `rec_low_${item.id}_${Date.now()}`,
        productName: item.name,
        inventoryItemId: item.id,
        quantity: suggestedQty,
        unit: item.unit,
        estimatedPricePaise: item.purchasePricePaise,
        priority,
        reason: `Below minimum threshold: ${item.quantity} ${item.unit} remaining (minimum threshold configured: ${item.minThreshold} ${item.unit}).`,
        status: 'planned',
        createdAt: new Date().toISOString(),
        isEssential,
        isAutoGenerated: true,
      })
      continue
    }

    // 3. Expiring soon reminder: DO NOT automatically create a purchase recommendation
    // if there is adequate stock! Consumption alert is surfaced in inventory instead.
    if (isExpiringSoon && daysUntilExpiry !== undefined) {
      // Intentionally do NOT recommend buying more while user still has expiring stock!
      // This strictly prevents unnecessary duplicate spending.
    }
  }

  // Sort recommendations by priority (highest -> high -> medium -> low)
  const priorityOrder: Record<ShoppingPriority, number> = {
    highest: 1,
    high: 2,
    medium: 3,
    low: 4,
  }

  return recommendations.sort(
    (a, b) => priorityOrder[a.priority] - priorityOrder[b.priority]
  )
}

/**
 * Evaluates the affordability of planned shopping list purchases against the authoritative financial ledger.
 * Adheres strictly to financial rules:
 * - Internal transfers are excluded from spending.
 * - Refunds are not treated as income.
 * - Failed transactions are excluded from spending.
 * - Pending transactions are separated from confirmed spending.
 * - Does not call estimated cash flow an actual bank balance.
 * - Explains clearly when budget is not configured.
 */
export function evaluateShoppingBudget(
  shoppingList: ShoppingListItem[],
  transactions: Transaction[],
  userBudgetLimitPaise?: number
): BudgetAwareShoppingEvaluation {
  const summary = calculateFinancialSummary(transactions)

  // Sum planned purchase costs for all uncompleted items
  let plannedShoppingCostsPaise = 0
  for (const item of shoppingList) {
    if (item.status === 'planned' && item.estimatedPricePaise && item.estimatedPricePaise > 0) {
      plannedShoppingCostsPaise = addPaise(
        plannedShoppingCostsPaise,
        item.estimatedPricePaise * item.quantity
      )
    }
  }

  const confirmedSpendingPaise = summary.totalConfirmedExpenses
  const pendingTransactionsPaise = summary.totalPendingExpenses
  const estimatedSpendableBufferPaise = summary.estimatedSpendable
  const hasBudgetConfigured =
    userBudgetLimitPaise !== undefined && Number.isFinite(userBudgetLimitPaise) && userBudgetLimitPaise > 0

  const warnings: string[] = []

  let isAffordable: boolean | 'unknown' = true
  let summaryExplanation = ''

  if (!hasBudgetConfigured) {
    // If no budget limit is configured, clearly explain
    if (estimatedSpendableBufferPaise >= plannedShoppingCostsPaise) {
      summaryExplanation = `User budget limit is not configured. Based on your estimated cash flow buffer of ${formatPaise(
        estimatedSpendableBufferPaise
      )}, planned purchases (${formatPaise(plannedShoppingCostsPaise)}) appear manageable.`
    } else {
      isAffordable = false
      summaryExplanation = `User budget limit is not configured. Your planned shopping costs (${formatPaise(
        plannedShoppingCostsPaise
      )}) exceed your estimated spendable buffer (${formatPaise(estimatedSpendableBufferPaise)}).`
    }
  } else {
    // Budget is configured
    const projectedTotalExpenses = addPaise(confirmedSpendingPaise, plannedShoppingCostsPaise)
    const budgetLimit = userBudgetLimitPaise!

    if (projectedTotalExpenses <= budgetLimit) {
      isAffordable = true
      const remainingBudget = budgetLimit - projectedTotalExpenses
      summaryExplanation = `Within configured monthly budget: Confirmed spending (${formatPaise(
        confirmedSpendingPaise
      )}) + Planned items (${formatPaise(plannedShoppingCostsPaise)}) leaves ${formatPaise(
        remainingBudget
      )} buffer before reaching your ₹${(budgetLimit / 100).toFixed(0)} limit.`
    } else {
      isAffordable = false
      const overage = projectedTotalExpenses - budgetLimit
      summaryExplanation = `Planned purchases exceed your configured budget limit by ${formatPaise(
        overage
      )}. Confirmed spending is ${formatPaise(confirmedSpendingPaise)} out of ₹${(
        budgetLimit / 100
      ).toFixed(0)}.`
    }
  }

  if (pendingTransactionsPaise > 0) {
    warnings.push(
      `Note: ${formatPaise(
        pendingTransactionsPaise
      )} in pending/unsettled transactions are pending bank clearance and not yet counted in confirmed spending.`
    )
  }

  return {
    plannedShoppingCostsPaise,
    confirmedSpendingPaise,
    pendingTransactionsPaise,
    userBudgetLimitPaise: hasBudgetConfigured ? userBudgetLimitPaise : undefined,
    estimatedSpendableBufferPaise,
    hasBudgetConfigured,
    isAffordable,
    summaryExplanation,
    warnings,
  }
}
